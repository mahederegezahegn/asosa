import React, { useState, useEffect, useRef, useMemo } from 'react';
import { Student, MealCard } from '../types/gate';
import { 
  CreditCard, 
  X, 
  Sparkles, 
  ScanLine, 
  Camera, 
  CameraOff, 
  AlertTriangle, 
  CheckCircle2, 
  Loader2,
  RefreshCw,
  ShieldAlert
} from 'lucide-react';
import { 
  BrowserMultiFormatReader, 
  BarcodeFormat, 
  DecodeHintType 
} from '@zxing/library';

interface IssueMealCardModalProps {
  student: Student;
  existingCard?: MealCard;
  mode: 'issue' | 'replace';
  existingMealCards: MealCard[];
  onConfirm: (studentId: string, oldCardNumber: string | undefined, newCardNumber: string) => Promise<void>;
  onClose: () => void;
}

export const IssueMealCardModal: React.FC<IssueMealCardModalProps> = ({
  student,
  existingCard,
  mode,
  existingMealCards,
  onConfirm,
  onClose,
}) => {
  const [method, setMethod] = useState<'auto' | 'manual'>('auto');
  const [manualCode, setManualCode] = useState('');
  const [isProcessing, setIsProcessing] = useState(false);
  const [error, setError] = useState<string | null>(null);

  // Camera state
  const [isCameraActive, setIsCameraActive] = useState(false);
  const [cameraError, setCameraError] = useState<string | null>(null);

  const inputRef = useRef<HTMLInputElement | null>(null);
  const videoRef = useRef<HTMLVideoElement | null>(null);
  const streamRef = useRef<MediaStream | null>(null);
  const zxingReaderRef = useRef<BrowserMultiFormatReader | null>(null);
  const animFrameIdRef = useRef<number | null>(null);

  // Auto-generate next unique card number (e.g. MC-000123)
  const autoGeneratedCode = useMemo(() => {
    let maxNum = 100;
    existingMealCards.forEach((c) => {
      const match = c.cardNumber.match(/^MC-(\d+)$/i);
      if (match && match[1]) {
        const num = parseInt(match[1], 10);
        if (!isNaN(num) && num > maxNum) {
          maxNum = num;
        }
      }
    });
    const nextNum = maxNum + 1;
    return `MC-${String(nextNum).padStart(6, '0')}`;
  }, [existingMealCards]);

  const targetCardNumber = method === 'auto' ? autoGeneratedCode : manualCode.trim().toUpperCase();

  const handleStartCamera = async () => {
    setCameraError(null);
    try {
      const stream = await navigator.mediaDevices.getUserMedia({
        video: { facingMode: { ideal: 'environment' } },
      });
      streamRef.current = stream;
      if (videoRef.current) {
        videoRef.current.srcObject = stream;
        await videoRef.current.play();
      }
      setIsCameraActive(true);

      const hints = new Map();
      hints.set(DecodeHintType.POSSIBLE_FORMATS, [BarcodeFormat.CODE_128, BarcodeFormat.CODE_39]);
      const reader = new BrowserMultiFormatReader(hints);
      zxingReaderRef.current = reader;

      const scanLoop = () => {
        if (!videoRef.current || videoRef.current.readyState < 2) {
          animFrameIdRef.current = requestAnimationFrame(scanLoop);
          return;
        }
        try {
          const res = reader.decode(videoRef.current);
          if (res && res.getText()) {
            const scanned = res.getText().trim().toUpperCase();
            setManualCode(scanned);
            stopCamera();
            return;
          }
        } catch {}
        animFrameIdRef.current = requestAnimationFrame(scanLoop);
      };
      animFrameIdRef.current = requestAnimationFrame(scanLoop);
    } catch (err) {
      console.error('Camera open failed:', err);
      setCameraError('Camera access denied or unavailable.');
      setIsCameraActive(false);
    }
  };

  const stopCamera = () => {
    if (animFrameIdRef.current) {
      cancelAnimationFrame(animFrameIdRef.current);
      animFrameIdRef.current = null;
    }
    if (streamRef.current) {
      streamRef.current.getTracks().forEach((t) => t.stop());
      streamRef.current = null;
    }
    if (zxingReaderRef.current) {
      zxingReaderRef.current.reset();
      zxingReaderRef.current = null;
    }
    if (videoRef.current) {
      videoRef.current.srcObject = null;
    }
    setIsCameraActive(false);
  };

  useEffect(() => {
    return () => {
      stopCamera();
    };
  }, []);

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError(null);

    if (method === 'manual' && !manualCode.trim()) {
      setError('Please enter or scan a physical card barcode number.');
      return;
    }

    // Check if target code is already in use by another active card
    const cleanTarget = targetCardNumber;
    const existingUsed = existingMealCards.find(
      (c) => c.cardNumber.toUpperCase() === cleanTarget && c.status === 'ACTIVE'
    );
    if (existingUsed && existingUsed.studentId !== student.id) {
      setError(`Card number "${cleanTarget}" is already assigned to student ${existingUsed.studentName || existingUsed.studentId}.`);
      return;
    }

    setIsProcessing(true);
    try {
      await onConfirm(student.id, mode === 'replace' ? existingCard?.cardNumber : undefined, cleanTarget);
      onClose();
    } catch (err: unknown) {
      console.error('Issue meal card error:', err);
      setError(err instanceof Error ? err.message : String(err));
    } finally {
      setIsProcessing(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-4 bg-black/50 backdrop-blur-xs overflow-y-auto">
      <div className="bg-white border border-gray-200 rounded-lg shadow-xl max-w-lg w-full flex flex-col text-gray-900 max-h-[94vh] overflow-y-auto">
        {/* Header */}
        <div className="p-5 border-b border-gray-200 flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className={`w-9 h-9 rounded-lg flex items-center justify-center shrink-0 ${
              mode === 'replace' ? 'bg-red-50 text-[#DC2626] border border-red-200' : 'bg-green-50 text-[#15803D] border border-green-200'
            }`}>
              {mode === 'replace' ? <RefreshCw className="w-5 h-5" /> : <CreditCard className="w-5 h-5" />}
            </div>
            <div>
              <h2 className="text-base font-bold text-gray-900">
                {mode === 'replace' ? 'Replace Lost Meal Card' : 'Issue Meal Card'}
              </h2>
              <p className="text-xs text-gray-500">
                Student: <strong>{student.fullName}</strong> ({student.id})
              </p>
            </div>
          </div>

          <button
            type="button"
            onClick={onClose}
            className="p-1.5 text-gray-400 hover:text-gray-700 hover:bg-gray-100 rounded-md transition-colors cursor-pointer"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Form Body */}
        <form onSubmit={handleSubmit} className="p-6 space-y-5">
          {/* Replace Warning Banner */}
          {mode === 'replace' && (
            <div className="p-3.5 rounded-md bg-red-50 border border-red-200 text-xs text-[#DC2626] flex items-start gap-2.5">
              <ShieldAlert className="w-4 h-4 shrink-0 mt-0.5" />
              <div>
                <strong className="block font-bold">Lost Card Revocation Notice</strong>
                Current active card <strong>{existingCard?.cardNumber || 'MC-PREVIOUS'}</strong> will be marked as <span className="underline font-bold">BLOCKED</span> immediately so it can no longer be redeemed in the dining hall.
              </div>
            </div>
          )}

          {error && (
            <div className="p-3 rounded-md bg-red-50 border border-red-200 text-[#DC2626] text-xs font-semibold flex items-center gap-2">
              <AlertTriangle className="w-4 h-4 shrink-0" />
              <span>{error}</span>
            </div>
          )}

          {/* Student Badge Preview Strip */}
          <div className="p-3 bg-gray-50 rounded-md border border-gray-200 flex items-center justify-between text-xs">
            <div className="flex items-center gap-2.5">
              {student.photo && (student.photo.startsWith('http') || student.photo.startsWith('data:')) ? (
                <img src={student.photo} alt={student.fullName} className="w-9 h-9 rounded object-cover border border-gray-300" />
              ) : (
                <div className="w-9 h-9 rounded bg-[#15803D] text-white font-bold flex items-center justify-center text-xs">
                  {student.fullName.split(' ').map(w => w[0]).slice(0, 2).join('')}
                </div>
              )}
              <div>
                <div className="font-bold text-gray-900">{student.fullName}</div>
                <div className="text-[11px] text-gray-500">{student.department} · {student.level}</div>
              </div>
            </div>
            <span className="text-[10px] font-bold px-2 py-0.5 rounded border border-gray-300 bg-white text-gray-700">
              ID: {student.id}
            </span>
          </div>

          {/* Selection: Auto vs Manual */}
          <div className="space-y-3">
            <label className="block text-xs font-bold text-gray-700 uppercase tracking-wider">
              Card Barcode Number Assignment
            </label>

            <div className="grid grid-cols-2 gap-3">
              <button
                type="button"
                onClick={() => setMethod('auto')}
                className={`p-3 rounded-lg border text-left transition-all cursor-pointer flex items-center justify-between ${
                  method === 'auto'
                    ? 'border-[#15803D] bg-green-50/60 font-semibold'
                    : 'border-gray-200 bg-white hover:bg-gray-50'
                }`}
              >
                <div>
                  <div className="text-xs font-bold text-gray-900 flex items-center gap-1.5">
                    <Sparkles className="w-3.5 h-3.5 text-[#15803D]" />
                    <span>Auto-Generate</span>
                  </div>
                  <div className="text-[11px] font-mono text-[#15803D] font-bold mt-1">
                    {autoGeneratedCode}
                  </div>
                </div>
                {method === 'auto' && <CheckCircle2 className="w-4 h-4 text-[#15803D] shrink-0" />}
              </button>

              <button
                type="button"
                onClick={() => {
                  setMethod('manual');
                  setTimeout(() => inputRef.current?.focus(), 100);
                }}
                className={`p-3 rounded-lg border text-left transition-all cursor-pointer flex items-center justify-between ${
                  method === 'manual'
                    ? 'border-[#15803D] bg-green-50/60 font-semibold'
                    : 'border-gray-200 bg-white hover:bg-gray-50'
                }`}
              >
                <div>
                  <div className="text-xs font-bold text-gray-900 flex items-center gap-1.5">
                    <ScanLine className="w-3.5 h-3.5 text-gray-700" />
                    <span>Type / Scan Physical</span>
                  </div>
                  <div className="text-[10px] text-gray-500 mt-1">
                    Custom physical PVC barcode
                  </div>
                </div>
                {method === 'manual' && <CheckCircle2 className="w-4 h-4 text-[#15803D] shrink-0" />}
              </button>
            </div>
          </div>

          {/* Manual / USB Scan Barcode Field */}
          {method === 'manual' && (
            <div className="space-y-2 pt-1">
              <div className="flex items-center justify-between">
                <label className="block text-xs font-semibold text-gray-700">
                  Physical Card Barcode Number
                </label>
                <button
                  type="button"
                  onClick={isCameraActive ? stopCamera : handleStartCamera}
                  className="flex items-center gap-1 text-xs text-[#15803D] font-semibold hover:underline cursor-pointer"
                >
                  {isCameraActive ? <CameraOff className="w-3.5 h-3.5" /> : <Camera className="w-3.5 h-3.5" />}
                  <span>{isCameraActive ? 'Stop Camera' : 'Camera Scan'}</span>
                </button>
              </div>

              {isCameraActive && (
                <div className="relative rounded-lg overflow-hidden bg-gray-900 border border-gray-300 aspect-video max-h-48 flex items-center justify-center">
                  <video ref={videoRef} className="w-full h-full object-cover" playsInline muted />
                  <div className="absolute inset-0 pointer-events-none flex items-center justify-center">
                    <div className="w-4/5 h-20 border border-dashed border-white/80 rounded-md flex items-center justify-center">
                      <div className="w-full h-0.5 bg-[#DC2626]" />
                    </div>
                  </div>
                </div>
              )}

              {cameraError && (
                <div className="text-xs text-red-600 font-medium">{cameraError}</div>
              )}

              <input
                ref={inputRef}
                type="text"
                value={manualCode}
                onChange={(e) => setManualCode(e.target.value)}
                placeholder="Scan or type barcode (e.g. MC-009281)..."
                className="w-full px-3 py-2 bg-white border border-gray-300 rounded-md font-mono text-sm text-gray-900 focus:outline-none focus:border-[#15803D]"
              />
            </div>
          )}

          {/* Submit Action */}
          <div className="pt-3 border-t border-gray-200 flex items-center justify-end gap-3">
            <button
              type="button"
              onClick={onClose}
              disabled={isProcessing}
              className="px-4 py-2 text-xs font-semibold text-gray-700 bg-white border border-gray-300 hover:bg-gray-50 rounded-md cursor-pointer disabled:opacity-50"
            >
              Cancel
            </button>

            <button
              type="submit"
              disabled={isProcessing}
              className={`flex items-center gap-2 px-4 py-2 text-xs font-semibold text-white rounded-md shadow-xs transition-colors cursor-pointer disabled:opacity-50 ${
                mode === 'replace' ? 'bg-[#DC2626] hover:bg-red-700' : 'bg-[#15803D] hover:bg-[#166534]'
              }`}
            >
              {isProcessing ? (
                <>
                  <Loader2 className="w-4 h-4 animate-spin" />
                  <span>Processing...</span>
                </>
              ) : (
                <>
                  <CreditCard className="w-4 h-4" />
                  <span>{mode === 'replace' ? 'Confirm Replacement' : 'Issue Meal Card'}</span>
                </>
              )}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
};
